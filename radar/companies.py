_CORP_MARK_RE = re.compile(r"\(주\)|㈜|주식회사")
_SEPARATORS = " (·/"


def _fold(name: str) -> str:
    return re.sub(r"\s+", " ", name).strip().casefold()


def in_group(company: str | None, majors: set[str]) -> bool:
    """company 가 majors 의 어느 이름과 같거나, 그 이름으로 시작하고 바로 뒤가 공백·괄호·구분 기호인지."""
    if not company:
        return False
    # 사이트 표기 그대로와, '(주)'·'㈜'·'주식회사' 를 뗀 표기 둘 다로 본다('(주)한화 글로벌부문' → '한화 글로벌부문')
    names = {n for n in (_fold(company), _fold(_CORP_MARK_RE.sub(" ", company))) if n}
    for m in majors:
        exact = m.startswith("=")   # '=KT' 는 이름이 정확히 같을 때만. 'kt netcore' 처럼 뒤에 다른 회사명이 붙는 그룹에 쓴다
        key = _fold(m[1:] if exact else m)
        for name in names:
            if name == key or (not exact and name.startswith(key) and name[len(key)] in _SEPARATORS):
                return True
    return False
